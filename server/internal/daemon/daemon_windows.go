//go:build windows

package daemon

import (
	"fmt"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"
	"time"

	"golang.org/x/sys/windows/registry"
	"orbit/internal/config"
)

const (
	runKeyPath      = `Software\Microsoft\Windows\CurrentVersion\Run`
	runKeyValName   = "OrbitDaemon"
	vbsFileName     = "orbit-daemon.vbs"
)

func getServiceTypeDescription() string {
	return "Inicio de Usuario (HKCU Run - VBS Silencioso)"
}

func getVBSPath() string {
	appData := os.Getenv("APPDATA")
	if appData == "" {
		appData = filepath.Join(os.Getenv("USERPROFILE"), "AppData", "Roaming")
	}
	return filepath.Join(appData, "Orbit", vbsFileName)
}

func isServiceInstalled() bool {
	k, err := registry.OpenKey(registry.CURRENT_USER, runKeyPath, registry.QUERY_VALUE)
	if err != nil {
		return false
	}
	defer k.Close()

	val, _, err := k.GetStringValue(runKeyValName)
	if err != nil || val == "" {
		return false
	}
	return true
}

// Install registers Orbit to automatically launch silently on user logon
func Install(cfg *config.Config, exePath string) error {
	if exePath == "" {
		var err error
		exePath, err = os.Executable()
		if err != nil {
			return err
		}
	}
	exePath, _ = filepath.Abs(filepath.Clean(exePath))
	exeDir := filepath.Dir(exePath)

	vbsPath := getVBSPath()
	if err := os.MkdirAll(filepath.Dir(vbsPath), 0755); err != nil {
		return fmt.Errorf("error al crear directorio para el script del demonio: %w", err)
	}

	// Create VBScript launcher that invokes Orbit with 0 console window
	vbsContent := fmt.Sprintf(`' Generated by Orbit Developer Cockpit
Set WshShell = CreateObject("WScript.Shell")
WshShell.CurrentDirectory = "%s"
WshShell.Run """%s"" -no-open", 0, False
`, strings.ReplaceAll(exeDir, `\`, `\\`), strings.ReplaceAll(exePath, `\`, `\\`))

	if err := os.WriteFile(vbsPath, []byte(vbsContent), 0644); err != nil {
		return fmt.Errorf("error escribiendo script vbs del servicio: %w", err)
	}

	// Register in HKCU\Software\Microsoft\Windows\CurrentVersion\Run
	k, err := registry.OpenKey(registry.CURRENT_USER, runKeyPath, registry.QUERY_VALUE|registry.SET_VALUE)
	if err != nil {
		return fmt.Errorf("error abriendo clave de registro Run: %w", err)
	}
	defer k.Close()

	cmdVal := fmt.Sprintf(`wscript.exe //B //Nologo "%s"`, vbsPath)
	if err := k.SetStringValue(runKeyValName, cmdVal); err != nil {
		return fmt.Errorf("error guardando valor de registro en Run: %w", err)
	}

	// If not currently running, launch it right now
	port := cfg.Port
	if port == "" {
		port = "8080"
	}
	if findPIDOnPort(port) == 0 {
		_ = Start(cfg, exePath)
	}

	return nil
}

// Uninstall unregisters the background service and stops the running daemon
func Uninstall(cfg *config.Config) error {
	// 1. Stop running daemon
	_ = Stop(cfg)

	// 2. Remove registry entry
	k, err := registry.OpenKey(registry.CURRENT_USER, runKeyPath, registry.QUERY_VALUE|registry.SET_VALUE)
	if err == nil {
		defer k.Close()
		_ = k.DeleteValue(runKeyValName)
	}

	// 3. Remove VBScript launcher
	vbsPath := getVBSPath()
	_ = os.Remove(vbsPath)

	return nil
}

// Start launches the daemon in background without any console window
func Start(cfg *config.Config, exePath string) error {
	port := cfg.Port
	if port == "" {
		port = "8080"
	}

	// Check if already running
	if pid := findPIDOnPort(port); pid > 0 {
		return fmt.Errorf("Orbit Daemon ya está ejecutándose en el puerto %s (PID: %d)", port, pid)
	}

	if exePath == "" {
		var err error
		exePath, err = os.Executable()
		if err != nil {
			return err
		}
	}
	exePath, _ = filepath.Abs(filepath.Clean(exePath))
	exeDir := filepath.Dir(exePath)

	vbsPath := getVBSPath()
	var cmd *exec.Cmd

	if _, err := os.Stat(vbsPath); err == nil {
		cmd = exec.Command("wscript.exe", "//B", "//Nologo", vbsPath)
	} else {
		cmd = exec.Command(exePath, "-no-open")
		cmd.Dir = exeDir
		cmd.SysProcAttr = &syscall.SysProcAttr{
			HideWindow:    true,
			CreationFlags: 0x08000000 | 0x00000200, // CREATE_NO_WINDOW | CREATE_NEW_PROCESS_GROUP
		}
	}

	if err := cmd.Start(); err != nil {
		return fmt.Errorf("error al iniciar proceso en segundo plano: %w", err)
	}

	// Poll health endpoint for up to 3 seconds to confirm startup
	client := &http.Client{Timeout: 300 * time.Millisecond}
	deadline := time.Now().Add(3 * time.Second)
	for time.Now().Before(deadline) {
		time.Sleep(200 * time.Millisecond)
		resp, err := client.Get(fmt.Sprintf("http://127.0.0.1:%s/api/health", port))
		if err == nil && resp.StatusCode == http.StatusOK {
			_ = resp.Body.Close()
			return nil
		}
		if resp != nil {
			_ = resp.Body.Close()
		}
	}

	return nil
}

// Stop terminates the running daemon process on the configured port
func Stop(cfg *config.Config) error {
	port := cfg.Port
	if port == "" {
		port = "8080"
	}

	pid := findPIDOnPort(port)
	if pid == 0 {
		return fmt.Errorf("no se encontró ningún proceso de Orbit escuchando en el puerto %s", port)
	}

	killCmd := exec.Command("taskkill", "/F", "/PID", strconv.Itoa(pid))
	killCmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true, CreationFlags: 0x08000000}
	if err := killCmd.Run(); err != nil {
		return fmt.Errorf("error terminando proceso con PID %d: %w", pid, err)
	}

	// Wait up to 2 seconds for port to clear
	deadline := time.Now().Add(2 * time.Second)
	for time.Now().Before(deadline) {
		time.Sleep(150 * time.Millisecond)
		if findPIDOnPort(port) == 0 {
			return nil
		}
	}

	return nil
}

func findPIDOnPort(port string) int {
	out, err := exec.Command("netstat", "-ano").Output()
	if err != nil {
		return 0
	}

	target := fmt.Sprintf(":%s", port)
	lines := strings.Split(string(out), "\n")
	myPID := os.Getpid()

	for _, line := range lines {
		if strings.Contains(line, target) && strings.Contains(line, "LISTENING") {
			fields := strings.Fields(line)
			if len(fields) >= 5 {
				pidStr := fields[len(fields)-1]
				if pid, err := strconv.Atoi(pidStr); err == nil && pid > 4 && pid != myPID {
					return pid
				}
			}
		}
	}
	return 0
}
